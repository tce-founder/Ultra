#!/usr/bin/env python3
"""
Race fuelling arithmetic and a gut-training progression, over graded inputs.

WHY THIS IS CODE. A fuelling plan is arithmetic that people do in their heads,
wrongly, in two specific ways this module exists to stop:

  1. GRAMS OF PRODUCT VERSUS GRAMS OF CARBOHYDRATE. A 40 g gel is not 40 g of
     carbohydrate, and a plan counted in gels can be out by a factor of two.
  2. THE PLAN IS BUILT FOR THE TARGET AND NOT FOR THE FALLBACK. The fallback is
     the part that gets used, and most plans do not have one.

WHAT THIS DOES NOT DO. It does not tell you your rate. The rate comes from what
the athlete has tolerated in training, not from this file and not from a study —
see advisory/kb/frameworks/carbohydrate-fueling-ladder.md. Passing in 120 because
a trial in twenty gut-trained elite men used it is exactly the misuse the
`population` field on every Input here is trying to make visible.

It also does not compute a fluid target, deliberately. The consensus position is
drink-to-thirst, and a millilitres-per-hour number generated by a program is
precisely the scheduled-drinking behaviour identified as the mechanism of
exercise-associated hyponatremia. Sodium is reported per hour as information; it
is not a target and is not prophylaxis. See
advisory/kb/frameworks/drink-to-thirst.md.

Usage:  python3 advisory/model/fueling.py        # runs the worked example
"""

from dataclasses import dataclass
from typing import List

from inputs import Input, derive


@dataclass(frozen=True)
class Product:
    """One item as actually carried. `carb_g` is CARBOHYDRATE, not product mass."""
    name: str
    carb_g: float
    sodium_mg: float = 0.0
    needs_water: bool = False   # True for anything that must be drunk to be eaten

    def __str__(self):
        w = " (needs water)" if self.needs_water else ""
        return f"{self.name}: {self.carb_g:g} g CHO, {self.sodium_mg:g} mg Na{w}"


def hourly_plan(products: List[Product], target_rate: Input):
    """Greedy selection of items summing as close as possible to the target rate
    without a large overshoot. Returns (items, achieved_rate).

    Greedy rather than optimal on purpose: a plan an athlete can remember beats a
    plan that is 3 g/h closer to a target that was itself an estimate.
    """
    chosen, total = [], 0.0
    for p in sorted(products, key=lambda x: -x.carb_g):
        while total + p.carb_g <= target_rate.value:
            chosen.append(p)
            total += p.carb_g
    # One partial top-up if it lands closer than stopping short.
    if chosen:
        smallest = min(products, key=lambda x: x.carb_g)
        if abs(total + smallest.carb_g - target_rate.value) < abs(total - target_rate.value):
            chosen.append(smallest)
            total += smallest.carb_g
    return chosen, total


def race_plan(duration_h: Input, target_rate: Input, products: List[Product]):
    """Total carbohydrate, per-hour composition, and the water dependency."""
    items, achieved = hourly_plan(products, target_rate)
    total_carb = derive(
        achieved * duration_h.value, "g carbohydrate",
        duration_h, target_rate,
        note="achieved hourly rate x duration. NOT the target rate x duration — "
             "the difference is what the products actually add up to.",
    )
    dry = sum(p.carb_g for p in items if not p.needs_water)
    return {
        "items_per_hour": items,
        "achieved_rate": achieved,
        "target_rate": target_rate,
        "shortfall": target_rate.value - achieved,
        "total_carb": total_carb,
        "sodium_per_hour": sum(p.sodium_mg for p in items),
        "carb_without_water": dry,
        "water_dependency": 1.0 - (dry / achieved) if achieved else 0.0,
    }


def fallback_ladder(target_rate: Input):
    """The step-down every plan needs and most do not have.

    Rungs are fractions of target. They are ASSERTED — coaching convention, not a
    measured schedule — and the fractions matter far less than the ladder
    existing at all.
    """
    steps = [
        (1.00, "target rate, planned products"),
        (0.75, "same rate band, different form — swap gel for chew, or chew for drink"),
        (0.50, "half rate, simplest tolerated product only"),
        (0.30, "liquid carbohydrate only, sipped"),
        (0.00, "stop fuelling, walk, settle 20-30 min, then restart at the 0.30 rung"),
    ]
    return [(round(f * target_rate.value), label) for f, label in steps]


def gut_training_schedule(current: Input, target: Input, step_g_per_week: float = 10.0):
    """Weeks of long-run progression from tolerated to target rate.

    ASSERTED. The +10 g/h per week convention is repeated across commercial
    coaching sources and is not established by any trial — see
    advisory/kb/frameworks/gut-training-protocol.md. What IS established is that
    intestinal adaptation occurs and can be fast.
    """
    weeks, rate, n = [], current.value, 1
    while rate < target.value:
        rate = min(rate + step_g_per_week, target.value)
        weeks.append((n, rate))
        n += 1
    return weeks


def _example():
    """A worked example. Every figure is labelled with where it came from, which
    is the point of the exercise as much as the arithmetic is."""
    duration = Input(14, "hours", "athlete estimate from a similar course", "UNVERIFIED",
                     population="this athlete", note="estimates on unfamiliar mountain courses are optimistic")
    tolerated = Input(55, "g carbohydrate/hour", "athlete's own long-run record", "VERIFIED",
                      population="this athlete, race intensity, 5 h session")
    target = Input(75, "g carbohydrate/hour", "carbohydrate-fueling-ladder, standard guidance band",
                   "REPORTED",
                   population="laboratory studies of trained cyclists and runners, events far shorter than this one")

    products = [
        Product("energy gel", carb_g=22, sodium_mg=50),
        Product("drink mix, 500 ml", carb_g=30, sodium_mg=300, needs_water=True),
        Product("chews, half pack", carb_g=12, sodium_mg=40),
    ]

    print("=" * 74)
    print("RACE FUELLING PLAN")
    print("=" * 74)
    for label, i in (("duration", duration), ("tolerated now", tolerated), ("target", target)):
        print(f"  {label:<16} {i}")

    plan = race_plan(duration, target, products)
    print(f"\n  Per hour ({plan['achieved_rate']:g} g CHO against a target of {target.value:g}, "
          f"shortfall {plan['shortfall']:g} g):")
    for p in plan["items_per_hour"]:
        print(f"    - {p}")
    print(f"\n  {plan['total_carb']}")
    print(f"  sodium/hour       {plan['sodium_per_hour']:g} mg  "
          f"(INFORMATION, not a target — see drink-to-thirst.md)")
    print(f"  water dependency  {plan['water_dependency']:.0%} of carbohydrate requires drinking")
    if plan["water_dependency"] > 0.5:
        print("    WARNING: over half the fuel needs water. In heat this couples fuelling to")
        print("    drinking and in cold it forces drinking to fuel. Carry a dry alternative.")

    print("\n  Fallback ladder (the rung that gets used):")
    for rate, label in fallback_ladder(target):
        print(f"    {rate:>3} g/h  {label}")

    print("\n  Gut training, +10 g/h per week on the long run only:")
    schedule = gut_training_schedule(tolerated, target)
    for week, rate in schedule:
        print(f"    week {week}: {rate:g} g/h")
    print(f"    -> {len(schedule)} weeks, in the specific block and not the taper.")

    print("\n  Provenance:")
    print(plan["total_carb"].explain(4))

    gap = target.value - tolerated.value
    print(f"\n  READ THIS. The total is graded {plan['total_carb'].grade} — and note WHICH input")
    print("  dragged it there. It is not the fuelling target, which is only REPORTED; it is the")
    print("  race duration, which is the athlete's own guess about an unfamiliar course. The")
    print("  weakest link in a fuelling plan is routinely the one nobody thinks of as a figure.")
    print(f"\n  Second reading: the only VERIFIED number here is the athlete's tolerated rate, and")
    print(f"  it is {gap:g} g/h below the plan. That gap is the gut-training block above — it is not")
    print("  something to assume away on race morning.")


if __name__ == "__main__":
    _example()
